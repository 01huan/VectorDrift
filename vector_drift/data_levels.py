"""Hand-designed campaign levels (fixed content only).

Rule: campaign levels are only ever added at the end, with the next id.
A level's id is its identity in saves (best time, clear reward,
achievements, coins, replays), so a released id is never renumbered and
never reused. The number the player sees is data.level_number; for a
campaign level it is the id.

Dynamic levels (the random level, id RANDOM_LEVEL_ID = 999, numbered right
after the last campaign level) live in :mod:`vector_drift.level_presets` and
are generated by :mod:`vector_drift.random_level`; see
:func:`vector_drift.data.get_level`.
"""

